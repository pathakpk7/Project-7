// Quick verification by format
const totals = {};
for (const m of allCombined) {
  if (!totals[m.format]) totals[m.format] = { innings: 0, runs: 0, hundreds: 0, fifties: 0, hs: 0 };
  totals[m.format].innings++;
  totals[m.format].runs += m.runs;
  if (m.runs >= 100) totals[m.format].hundreds++;
  else if (m.runs >= 50) totals[m.format].fifties++;
  if (m.runs > totals[m.format].hs) totals[m.format].hs = m.runs;
}

console.log("Verified Totals:", JSON.stringify(totals, null, 2));
