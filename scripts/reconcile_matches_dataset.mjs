// Combine all matches and ensure no duplicate match_ids
const allCombined = [...existingMatches];

function upsertMatches(missingList) {
  for (const m of missingList) {
    const exists = allCombined.some(x => x.match_id === m.match_id && x.innings_number === m.innings_number);
    if (!exists) {
      allCombined.push(m);
    }
  }
}

